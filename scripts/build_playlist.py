#!/usr/bin/env python3
"""
Build Playlist/bdott.m3u from the OTT Plus live-tv API.

- Follows every "next" cursor until the API stops returning one.
- Keeps only channels whose stream URL actually responds with a playable HLS manifest.
- The API URL comes from the OTT_API_URL environment variable (GitHub Secret),
  so it is never written in the public repository.
- Logs only key names and counts, never stream URLs (Actions logs are public in public repos).
"""

import os
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from urllib.parse import urljoin

import requests

# ----------------------------------------------------------------------------
# Settings
# ----------------------------------------------------------------------------
API_URL = os.environ.get("OTT_API_URL", "").strip()
OUT_FILE = os.environ.get("OUT_FILE", "Playlist/bdott.m3u")
MAX_PAGES = int(os.environ.get("MAX_PAGES", "500"))
CHECK_WORKERS = int(os.environ.get("CHECK_WORKERS", "20"))
CHECK_TIMEOUT = float(os.environ.get("CHECK_TIMEOUT", "8"))

HEADER_LINES = [
    "#EXTM3U",
    "# PLAYLIST: Playlists",
    "# Generated By: Kallyan Biswas",
    "# Facebook: www.Facebook.com/kallyan.biswas.29",
    "# Telegram: https://t.me/iptvlinksm3u8",
]

HTTP_HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                  "(KHTML, like Gecko) Chrome/124.0 Safari/537.36",
    "Accept": "*/*",
}

LIST_KEYS = ("data", "items", "channels", "live_tvs", "liveTvs", "results", "list", "rows")
NEXT_KEYS = ("next", "next_page", "nextPage", "next_url", "nextUrl")
NAME_KEYS = ("name", "title", "channel_name", "channelName", "display_name")
LOGO_KEYS = ("logo", "logo_url", "logoUrl", "image", "thumbnail", "icon", "poster")
GROUP_KEYS = ("category", "categories", "group", "group_title", "genre", "genres")
STREAM_KEYS = ("m3u8", "stream_url", "streamUrl", "hls", "url", "link", "source", "sources",
               "stream", "streams", "file", "playback_url", "playbackUrl")


# ----------------------------------------------------------------------------
# Helpers for unknown JSON shapes
# ----------------------------------------------------------------------------
def log(msg):
    print(msg, flush=True)


def extract_items(payload):
    """Return the list of channel dicts from one API page."""
    if isinstance(payload, list):
        return [x for x in payload if isinstance(x, dict)]
    if not isinstance(payload, dict):
        return []
    for key in LIST_KEYS:
        value = payload.get(key)
        if isinstance(value, list):
            return [x for x in value if isinstance(x, dict)]
        if isinstance(value, dict):
            found = extract_items(value)
            if found:
                return found
    # Fallback: the longest list of dicts at top level
    best = []
    for value in payload.values():
        if isinstance(value, list) and value and isinstance(value[0], dict):
            if len(value) > len(best):
                best = value
    return best


def find_next(payload):
    """Return the next-page URL/cursor if the API gives one, else None."""
    if not isinstance(payload, dict):
        return None
    candidates = [payload]
    for container in ("meta", "links", "pagination", "paging", "page_info"):
        if isinstance(payload.get(container), dict):
            candidates.append(payload[container])
    for obj in candidates:
        for key in NEXT_KEYS:
            value = obj.get(key)
            if isinstance(value, dict):
                value = value.get("href") or value.get("url")
            if isinstance(value, str) and value.strip():
                return value.strip()
    return None


def first_string(obj, keys, prefer_substring=None):
    """Find the first usable http(s) string, searching nested dict/list values."""
    if isinstance(obj, dict):
        search_keys = keys if keys is not None else list(obj.keys())
        for key in search_keys:
            if key in obj:
                found = first_string(obj[key], keys=None, prefer_substring=prefer_substring)
                if found:
                    return found
        return ""
    if isinstance(obj, str):
        s = obj.strip()
        if s.startswith("http") and (prefer_substring is None or prefer_substring in s):
            return s
        return ""
    if isinstance(obj, list):
        for item in obj:
            found = first_string(item, keys=None, prefer_substring=prefer_substring)
            if found:
                return found
    return ""


def get_stream(ch):
    url = first_string(ch, STREAM_KEYS, prefer_substring=".m3u8")
    if not url:
        url = first_string(ch, STREAM_KEYS)
    return url


def get_name(ch):
    for key in NAME_KEYS:
        value = ch.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""


def get_logo(ch):
    for key in LOGO_KEYS:
        value = ch.get(key)
        if isinstance(value, str) and value.startswith("http"):
            return value.strip()
        if isinstance(value, dict):
            found = first_string(value, keys=None)
            if found:
                return found
    return ""


def get_group(ch):
    for key in GROUP_KEYS:
        value = ch.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
        if isinstance(value, dict) and isinstance(value.get("name"), str):
            return value["name"].strip()
        if isinstance(value, list) and value:
            first = value[0]
            if isinstance(first, str):
                return first.strip()
            if isinstance(first, dict) and isinstance(first.get("name"), str):
                return first["name"].strip()
    return "Others"


def clean(text):
    """Keep M3U attribute/title values on one line and free of quotes."""
    return str(text).replace('"', "'").replace("\n", " ").replace("\r", " ").strip()


# ----------------------------------------------------------------------------
# API scan
# ----------------------------------------------------------------------------
def fetch_all_channels(session):
    url = API_URL
    visited = set()
    channels = []
    for page_no in range(1, MAX_PAGES + 1):
        if not url or url in visited:
            break
        visited.add(url)
        resp = session.get(url, timeout=20)
        resp.raise_for_status()
        payload = resp.json()
        items = extract_items(payload)
        if page_no == 1:
            log(f"First page top-level keys: {sorted(payload.keys()) if isinstance(payload, dict) else 'list'}")
            if items:
                log(f"First channel keys: {sorted(items[0].keys())}")
        log(f"Page {page_no}: {len(items)} channels")
        channels.extend(items)
        next_value = find_next(payload)
        if not next_value:
            break
        url = urljoin(url, next_value)
    log(f"Pages scanned: {len(visited)}, raw channels: {len(channels)}")
    return channels


def is_working(session, url):
    """True when the stream answers 200 and returns real data (manifest or media)."""
    try:
        with session.get(url, timeout=CHECK_TIMEOUT, stream=True, allow_redirects=True) as r:
            if r.status_code != 200:
                return False
            chunk = next(r.iter_content(4096), b"")
            if not chunk:
                return False
            if ".m3u8" in url.lower() or b"#EXTM3U" in chunk[:512]:
                return b"#EXTM3U" in chunk[:512]
            return True
    except requests.RequestException:
        return False


def build_entries(channels):
    """Turn raw API items into unique, named entries with a stream URL."""
    seen_urls = set()
    entries = []
    for ch in channels:
        url = get_stream(ch)
        name = get_name(ch)
        if not url or not name or url in seen_urls:
            continue
        seen_urls.add(url)
        entries.append({
            "name": clean(name),
            "logo": clean(get_logo(ch)),
            "group": clean(get_group(ch)),
            "url": url,
        })
    return entries


def filter_working(entries):
    session = requests.Session()
    session.headers.update(HTTP_HEADERS)
    with ThreadPoolExecutor(max_workers=CHECK_WORKERS) as pool:
        results = list(pool.map(lambda e: is_working(session, e["url"]), entries))
    return [entry for entry, ok in zip(entries, results) if ok]


# ----------------------------------------------------------------------------
# Output
# ----------------------------------------------------------------------------
def write_playlist(entries):
    now = datetime.now(timezone.utc)
    lines = list(HEADER_LINES)
    lines.append(f"# Date: {now:%Y-%m-%d}")
    lines.append(f"# Time: {now:%H:%M} UTC")
    lines.append(f"# Total Channels: {len(entries)}")
    lines.append("")
    for e in entries:
        lines.append(
            f'#EXTINF:-1 tvg-id="" tvg-name="{e["name"]}" tvg-logo="{e["logo"]}" '
            f'group-title="{e["group"]}",{e["name"]}'
        )
        lines.append(e["url"])
    os.makedirs(os.path.dirname(OUT_FILE) or ".", exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    if not API_URL:
        log("ERROR: OTT_API_URL is not set (add it as a GitHub Secret).")
        return 1

    session = requests.Session()
    session.headers.update(HTTP_HEADERS)

    try:
        raw = fetch_all_channels(session)
    except (requests.RequestException, ValueError) as exc:
        log(f"ERROR: API scan failed: {type(exc).__name__}")
        return 1

    entries = build_entries(raw)
    log(f"Unique channels with stream URL: {len(entries)}")

    working = filter_working(entries)
    log(f"Working channels: {len(working)} / {len(entries)}")

    if not working:
        log("No working channels found. Keeping the previous playlist unchanged.")
        return 1

    write_playlist(working)
    log(f"Wrote {OUT_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
