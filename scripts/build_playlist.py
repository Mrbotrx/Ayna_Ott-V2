#!/usr/bin/env python3
import os
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from urllib.parse import urljoin

import requests

# ----------------------------------------------------------------------------
# Settings
# ----------------------------------------------------------------------------
API_URL = os.environ.get("OTT_API_URL", "").strip()
OUT_FILE = os.environ.get("OUT_FILE", "Playlist/bdott.m3u")
MAX_PAGES = int(os.environ.get("MAX_PAGES", "500"))
CHECK_WORKERS = int(os.environ.get("CHECK_WORKERS", "20"))
CHECK_TIMEOUT = float(os.environ.get("CHECK_TIMEOUT", "8"))

HEADER_LINES = [
    "#EXTM3U",
    "# PLAYLIST: Playlists",
    "# Generated By: Kallyan Biswas",
    "# Facebook: www.Facebook.com/kallyan.biswas.29",
    "# Telegram: https://t.me/iptvlinksm3u8",
]

# Fixed entry written once at the top of the playlist (group "All").
INTRO_ENTRY = {
    "name": "Main owners Tv",
    "logo": "https://raw.githubusercontent.com/Mrbotrx/Mrbotrx/refs/heads/main/IPTV_LINKS_LOGO.jpg",
    "group": "All",
    "url": "https://github.com/Mrbotrx/Mrbotrx/raw/refs/heads/main/IPTV_LINKS_VIDEO.mp4",
}

HTTP_HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                  "(KHTML, like Gecko) Chrome/124.0 Safari/537.36",
    "Accept": "*/*",
}

PAGINATOR_KEYS = ("sections_paginator", "paginator", "pagination", "paging", "meta", "links", "page_info")
NEXT_KEYS = ("next", "next_page", "nextPage", "next_url", "nextUrl")
NAME_KEYS = ("title", "name", "channel_name", "display_name")
LOGO_KEYS = ("thumbnail", "thumbnail_background", "tv_cover", "sm_image", "lg_image",
             "logo", "logo_url", "image", "icon", "poster")
GROUP_KEYS = ("category", "categories", "group", "group_title", "genre", "genres")
STREAM_KEYS = ("url", "m3u8", "stream_url", "streamUrl", "hls", "link", "source", "sources",
               "stream", "streams", "file", "playback_url", "playbackUrl")
LIST_KEYS = ("data", "items", "channels", "live_tvs", "liveTvs", "results", "list", "rows")


# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------
def log(msg):
    print(msg, flush=True)


def clean(text):
    """Keep M3U attribute/title values on one line and free of quotes."""
    return str(text).replace('"', "'").replace("\n", " ").replace("\r", " ").strip()


def pick_http(obj, keys):
    """First top-level http(s) string under the given keys."""
    if not isinstance(obj, dict):
        return ""
    for key in keys:
        value = obj.get(key)
        if isinstance(value, str) and value.strip().startswith("http"):
            return value.strip()
    return ""


def get_group_name(obj):
    """Category/group name if the object has one, else empty string."""
    if not isinstance(obj, dict):
        return ""
    for key in GROUP_KEYS:
        value = obj.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
        if isinstance(value, dict) and isinstance(value.get("name"), str):
            return value["name"].strip()
        if isinstance(value, list) and value:
            first = value[0]
            if isinstance(first, str) and first.strip():
                return first.strip()
            if isinstance(first, dict) and isinstance(first.get("name"), str):
                return first["name"].strip()
    return ""


def pick_logo(content, item):
    """Channel logo: 'thumbnail' first, then 'thumbnail_background', then other image keys."""
    for key in LOGO_KEYS:
        for obj in (content, item):
            url = pick_http(obj, (key,))
            if url:
                return url
    return ""


def normalize_item(item, section_title=""):
    """Flatten one API item (with nested content) into name, url, logo, group."""
    content = item.get("content") if isinstance(item.get("content"), dict) else {}
    name = (content.get("title") or item.get("title") or item.get("name") or "")
    url = pick_http(content, STREAM_KEYS) or pick_http(item, STREAM_KEYS)
    logo = pick_logo(content, item)
    group = get_group_name(content) or get_group_name(item) or section_title or "Others"
    return {
        "name": clean(name),
        "url": url,
        "logo": clean(logo),
        "group": clean(group),
    }


def extract_items(payload):
    """Fallback for pages that are not in the sections format."""
    if isinstance(payload, list):
        return [x for x in payload if isinstance(x, dict)]
    if not isinstance(payload, dict):
        return []
    for key in LIST_KEYS:
        value = payload.get(key)
        if isinstance(value, list):
            return [x for x in value if isinstance(x, dict)]
        if isinstance(value, dict):
            found = extract_items(value)
            if found:
                return found
    return []


def flatten_channels(payload):
    """Return normalized channels from one API page, going through result.sections[].items[]."""
    root = payload.get("result") if isinstance(payload, dict) and isinstance(payload.get("result"), dict) else payload
    sections = root.get("sections") if isinstance(root, dict) else None
    channels = []
    if isinstance(sections, list):
        for sec in sections:
            if not isinstance(sec, dict):
                continue
            title = str(sec.get("title") or "")
            for item in sec.get("items") or []:
                if isinstance(item, dict):
                    channels.append(normalize_item(item, title))
        return channels
    return [normalize_item(item) for item in extract_items(payload)]


def find_next(payload):
    """Return the next-page URL/cursor if the API gives one, else None."""
    roots = [payload]
    if isinstance(payload, dict) and isinstance(payload.get("result"), dict):
        roots.append(payload["result"])

    candidates = []
    for root in roots:
        if not isinstance(root, dict):
            continue
        candidates.append(root)
        for container in PAGINATOR_KEYS:
            value = root.get(container)
            if isinstance(value, dict):
                candidates.append(value)
                if isinstance(value.get("links"), dict):
                    candidates.append(value["links"])

    for obj in candidates:
        for key in NEXT_KEYS:
            value = obj.get(key)
            if isinstance(value, dict):
                value = value.get("href") or value.get("url")
            if isinstance(value, str) and value.strip():
                return value.strip()
    return None


# ----------------------------------------------------------------------------
# API scan
# ----------------------------------------------------------------------------
def fetch_all_channels(session):
    url = API_URL
    visited = set()
    channels = []
    for page_no in range(1, MAX_PAGES + 1):
        if not url or url in visited:
            break
        visited.add(url)
        resp = session.get(url, timeout=20)
        resp.raise_for_status()
        payload = resp.json()

        page_channels = flatten_channels(payload)

        if page_no == 1:
            log(f"First page top-level keys: {sorted(payload.keys()) if isinstance(payload, dict) else 'list'}")
            root = payload.get("result") if isinstance(payload, dict) else None
            if isinstance(root, dict):
                log(f"'result' keys: {sorted(root.keys())}")
                sections = root.get("sections")
                if isinstance(sections, list):
                    titles = [str(s.get("title", "")) for s in sections if isinstance(s, dict)]
                    log(f"Section titles: {titles}")
                    for sec in sections:
                        items = sec.get("items") if isinstance(sec, dict) else None
                        if items and isinstance(items[0], dict):
                            content = items[0].get("content")
                            log(f"First item keys: {sorted(items[0].keys())}")
                            if isinstance(content, dict):
                                log(f"First content keys: {sorted(content.keys())}")
                            break

        log(f"Page {page_no}: {len(page_channels)} items")
        channels.extend(page_channels)

        next_value = find_next(payload)
        if not next_value:
            break
        url = urljoin(url, next_value)

    log(f"Pages scanned: {len(visited)}, raw items: {len(channels)}")
    return channels


def is_working(session, url):
    """True when the stream answers 200 and returns real data (manifest or media)."""
    try:
        with session.get(url, timeout=CHECK_TIMEOUT, stream=True, allow_redirects=True) as r:
            if r.status_code != 200:
                return False
            chunk = next(r.iter_content(4096), b"")
            if not chunk:
                return False
            if ".m3u8" in url.lower() or b"#EXTM3U" in chunk[:512]:
                return b"#EXTM3U" in chunk[:512]
            return True
    except requests.RequestException:
        return False


def build_entries(channels):
    """Keep unique items that have a name and a stream URL."""
    seen_urls = set()
    entries = []
    for ch in channels:
        if not ch["url"] or not ch["name"] or ch["url"] in seen_urls or ch["url"] == INTRO_ENTRY["url"]:
            continue
        seen_urls.add(ch["url"])
        entries.append(ch)
    return entries


def filter_working(entries):
    session = requests.Session()
    session.headers.update(HTTP_HEADERS)
    with ThreadPoolExecutor(max_workers=CHECK_WORKERS) as pool:
        results = list(pool.map(lambda e: is_working(session, e["url"]), entries))
    return [entry for entry, ok in zip(entries, results) if ok]


# ----------------------------------------------------------------------------
# Output
# ----------------------------------------------------------------------------
def write_playlist(entries):
    now = datetime.now(timezone.utc)
    lines = list(HEADER_LINES)
    lines.append(f"# Date: {now:%Y-%m-%d}")
    lines.append(f"# Time: {now:%H:%M} UTC")
    lines.append(f"# Total Channels: {len(entries) + 1}")
    lines.append("")
    for e in [INTRO_ENTRY] + entries:
        lines.append(
            f'#EXTINF:-1 tvg-id="" tvg-name="{e["name"]}" tvg-logo="{e["logo"]}" '
            f'group-title="{e["group"]}",{e["name"]}'
        )
        lines.append(e["url"])
    os.makedirs(os.path.dirname(OUT_FILE) or ".", exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    if not API_URL:
        log("ERROR: OTT_API_URL is not set (add it as a GitHub Secret).")
        return 1

    session = requests.Session()
    session.headers.update(HTTP_HEADERS)

    try:
        raw = fetch_all_channels(session)
    except (requests.RequestException, ValueError) as exc:
        log(f"ERROR: API scan failed: {type(exc).__name__}")
        return 1

    entries = build_entries(raw)
    log(f"Unique channels with stream URL: {len(entries)}")

    working = filter_working(entries)
    log(f"Working channels: {len(working)} / {len(entries)}")

    if not working:
        log("No working channels found. Keeping the previous playlist unchanged.")
        return 1

    write_playlist(working)
    log(f"Wrote {OUT_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
